#!/usr/bin/env python3
"""Export the Gathering Storm gameplay rules the mod reads into a Lua fixture for offline tests.

Reads the game's cache database read-only and writes tests/fixtures/gameinfo.lua:
    return { Terrains = { {TerrainType = "...", ...}, ... }, ... }
Column names come from the database itself (pragma table_info), never typed by hand.

Usage: python3 -I tools/export_gameinfo.py [--db PATH] [--out PATH]
"""

import argparse
import os
import sqlite3
import sys

DEFAULT_DB = os.path.expanduser(
    "~/Library/Application Support/Sid Meier's Civilization VI/Firaxis Games/"
    "Sid Meier's Civilization VI/Cache/DebugGameplay.sqlite"
)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "tests", "fixtures", "gameinfo.lua")

TABLES = [
    "Terrains", "Features", "Resources", "Improvements",
    "Districts", "Districts_XP2", "DistrictReplaces", "ExcludedDistricts",
    "MutuallyExclusiveDistricts", "District_Adjacencies", "Adjacency_YieldChanges",
    "District_RequiredFeatures",
    "Terrain_YieldChanges", "Feature_YieldChanges", "Resource_YieldChanges",
    "Improvement_YieldChanges", "Improvement_BonusYieldChanges",
    "Improvement_ValidTerrains", "Improvement_ValidFeatures", "Improvement_ValidResources",
    "Improvement_Adjacencies",
    "Resource_ValidTerrains", "Resource_ValidFeatures", "Resource_Harvests", "Resource_Consumption",
    "Feature_Removes", "Feature_ValidTerrains", "CoastalLowlands", "RandomEvents", "GameSpeeds", "GlobalParameters",
    "Units", "Units_XP2",
    "Civilizations", "CivilizationTraits", "Leaders", "LeaderTraits", "Traits", "TraitModifiers",
    "Happinesses", "Technologies", "Civics", "Buildings", "Yields",
]


def lua_string(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_value(v):
    if isinstance(v, str):
        return lua_string(v)
    if isinstance(v, float):
        return repr(v)
    return str(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    if not os.path.exists(args.db):
        sys.exit(f"database not found: {args.db}")
    con = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    cur = con.cursor()

    if not cur.execute("select 1 from Districts where DistrictType = 'DISTRICT_CANAL'").fetchone():
        sys.exit("DISTRICT_CANAL is absent: the cache is not from a Gathering Storm game. "
                 "Load a Gathering Storm game once, then run again.")

    existing = {r[0] for r in cur.execute("select name from sqlite_master where type = 'table'")}
    lines = ["-- Generated by tools/export_gameinfo.py from DebugGameplay.sqlite. Do not edit.", "return {"]
    for table in TABLES:
        if table not in existing:
            print(f"warning: table {table} not found, skipped", file=sys.stderr)
            continue
        cols = [r[1] for r in cur.execute(f"pragma table_info({table})")]
        rows = cur.execute(f"select * from {table} order by rowid").fetchall()
        lines.append(f"  {table} = {{")
        for row in rows:
            fields = [f"{c} = {lua_value(v)}" for c, v in zip(cols, row) if v is not None]
            lines.append("    { " + ", ".join(fields) + " },")
        lines.append("  },")
    lines.append("}")
    con.close()

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
